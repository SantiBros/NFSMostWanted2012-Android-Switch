#!/usr/bin/env python3
"""Generate guest->host marshalling thunks for every OpenGL ES 2.0 entry point.

    tools/gen_gles.py /usr/include/GLES2/gl2.h src/hle/gles_gen.inc

Reads the Khronos gl2.h prototypes and writes src/hle/gles_gen.inc. Functions
that need more than pointer translation (client-side arrays, shader sources,
buffer mapping, strings) are listed in MANUAL and implemented in gles.cpp.

Every thunk works with the threaded GL queue (src/hle/gl_queue.h):
  - void calls with only scalar arguments are queued (glq::call);
  - void calls whose pointer argument is input data of a known size are queued
    with a copy of that data (PAYLOAD below);
  - everything else (return values, output pointers) runs on the GL thread
    while the caller waits (glq::call_sync).
"""
import re
import sys

MANUAL = {
    "glShaderSource", "glVertexAttribPointer", "glDrawElements", "glGetString",
    "glGetVertexAttribPointerv", "glBindBuffer", "glBindFramebuffer", "glGetIntegerv",
    "glDeleteBuffers",
    # 3D-scene scaling and GL state tracking (gles.cpp)
    "glDeleteFramebuffers", "glActiveTexture", "glBindTexture", "glDeleteTextures", "glTexImage2D",
    "glTexParameteri", "glBindRenderbuffer", "glDeleteRenderbuffers", "glRenderbufferStorage",
    "glFramebufferTexture2D", "glFramebufferRenderbuffer", "glViewport", "glScissor",
    "glCopyTexSubImage2D", "glReadPixels", "glPixelStorei", "glDrawArrays",
}
EXTRA = [  # OES extensions the game imports
    "GL_APICALL void *GL_APIENTRY glMapBufferOES (GLenum target, GLenum access);",
    "GL_APICALL GLboolean GL_APIENTRY glUnmapBufferOES (GLenum target);",
    "GL_APICALL void GL_APIENTRY glGetBufferPointervOES (GLenum target, GLenum pname, void **params);",
]
MANUAL |= {"glMapBufferOES", "glUnmapBufferOES", "glGetBufferPointervOES"}

# Input-data pointers of a known size: name -> (index of the pointer argument,
# C++ expression for its size in bytes, using the guest arguments a0, a1...).
PAYLOAD = {}
for n, k in (("1", 1), ("2", 2), ("3", 3), ("4", 4)):
    PAYLOAD[f"glUniform{n}fv"] = (2, f"(size_t)(s32)a1 * {4 * k}")
    PAYLOAD[f"glUniform{n}iv"] = (2, f"(size_t)(s32)a1 * {4 * k}")
    PAYLOAD[f"glVertexAttrib{n}fv"] = (1, f"{4 * k}")
for n, k in (("2", 4), ("3", 9), ("4", 16)):
    PAYLOAD[f"glUniformMatrix{n}fv"] = (3, f"(size_t)(s32)a1 * {4 * k}")
PAYLOAD["glBufferData"] = (2, "(size_t)(s32)a1")
PAYLOAD["glBufferSubData"] = (3, "(size_t)(s32)a2")
PAYLOAD["glTexSubImage2D"] = (8, "image_bytes((s32)a4, (s32)a5, a6, a7)")
PAYLOAD["glCompressedTexImage2D"] = (7, "(size_t)(s32)a6")
PAYLOAD["glCompressedTexSubImage2D"] = (8, "(size_t)(s32)a7")
PAYLOAD["glBindAttribLocation"] = (2, "std::strlen(mem::str(a2)) + 1")
# Must not be queued even though they have no results.
SYNC = {"glFinish"}

src = open(sys.argv[1]).read()
protos = re.findall(r"GL_APICALL[^;]*;", src) + EXTRA
out = ["// Generated by tools/gen_gles.py from GLES2/gl2.h. Do not edit.\n"]
regs = []
for p in protos:
    m = re.match(r"GL_APICALL\s+(.*?)\s*GL_APIENTRY\s+(\w+)\s*\((.*)\);", p, re.S)
    ret, name, params = m.group(1).strip(), m.group(2), m.group(3).strip()
    if name in MANUAL:
        continue
    plist = [] if params in ("void", "") else [x.strip() for x in params.split(",")]
    gargs, cargs, ptypes, has_ptr = [], [], [], False
    for i, prm in enumerate(plist):
        pm = re.match(r"(.*?)(\w+)$", prm)
        ptype = pm.group(1).strip()
        ptypes.append(ptype)
        if "*" in ptype:
            has_ptr = True
            gargs.append(f"u32 a{i}")
            cargs.append(f"({ptype})mem::ptr<void>(a{i})")
        elif ptype in ("GLfloat", "GLclampf"):
            gargs.append(f"float a{i}")
            cargs.append(f"a{i}")
        elif ptype in ("GLintptr", "GLsizeiptr"):
            gargs.append(f"u32 a{i}")
            cargs.append(f"({ptype})(s32)a{i}")
        else:
            gargs.append(f"u32 a{i}")
            cargs.append(f"({ptype})a{i}")
    sig = ", ".join(plist) if plist else "void"
    out.append(f"static {ret} (GL_APIENTRY *p_{name})({sig});")
    load = f'if (!p_{name}) p_{name} = (decltype(p_{name}))gl_proc("{name}");'
    head = f"{load} GL_TRACE(\"{name}\");"
    if "*" in ret:
        raise SystemExit(f"pointer return needs manual handling: {name}")
    if ret == "void" and name in PAYLOAD:
        idx, size = PAYLOAD[name]
        fields = [f"{ptypes[i]} a{i};" for i in range(len(plist)) if i != idx]
        init = ", ".join(cargs[i] for i in range(len(plist)) if i != idx)
        call = ", ".join(f"({ptypes[i]})d" if i == idx else f"a.a{i}" for i in range(len(plist)))
        out.append(
            f"static void g_{name}({', '.join(gargs)}) {{ {head}\n"
            f"    struct Args {{ {' '.join(fields)} }};\n"
            f"    glq::call_data<Args>([](const Args& a, const void* d) {{ p_{name}({call}); }}, Args{{{init}}},\n"
            f"                         a{idx} ? mem::ptr<void>(a{idx}) : nullptr, a{idx} ? {size} : 0);\n"
            f"}}")
    elif ret == "void" and not has_ptr and name not in SYNC:
        args = ", ".join([f"p_{name}"] + cargs)
        out.append(f"static void g_{name}({', '.join(gargs)}) {{ {head} glq::call({args}); }}")
    elif ret == "void":
        args = ", ".join([f"p_{name}"] + cargs)
        out.append(f"static void g_{name}({', '.join(gargs)}) {{ {head} glq::call_sync_void({args}); }}")
    else:
        args = ", ".join([f"p_{name}"] + cargs)
        out.append(f"static u32 g_{name}({', '.join(gargs)}) {{ {head} return (u32)glq::call_sync({args}); }}")
    regs.append(f'    REG("{name}", g_{name});')
out.append("\nstatic void register_generated() {")
out += regs
out.append("}\n")
open(sys.argv[2], "w").write("\n".join(out))
print(f"{len(regs)} generated thunks")
